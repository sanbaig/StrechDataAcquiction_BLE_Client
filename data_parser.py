
# ============================================================
# StretchSense BLE Acquisition System
# Data Parser
#
# 文件功能：
# 将 BLE 接收到的原始字节数据解析为 CH1 和 CH2 两个通道。
#
# 当前 nRF52832 固件的数据格式：
# Byte 0-1：CH1，16-bit unsigned integer
# Byte 2-3：CH2，16-bit unsigned integer
#
# 数据采用 Little-Endian（小端字节序）。
# ============================================================


class DataParser:

    # --------------------------------------------------------
    # 1. 初始化数据解析器
    # --------------------------------------------------------

    def __init__(self):

        # 每个数据包应包含 4 个字节
        # CH1 占 2 字节，CH2 占 2 字节
        self.packet_length = 4


    # --------------------------------------------------------
    # 2. 解析 BLE 数据包
    # --------------------------------------------------------

    def parse_packet(self, data):

        # 检查接收到的数据长度是否正确
        if len(data) != self.packet_length:

            # 如果不是 4 字节，则说明数据包格式异常
            raise ValueError(
                f"Invalid packet length: {len(data)} bytes"
            )

        # ----------------------------------------------------
        # 提取 CH1 数据
        # ----------------------------------------------------

        # 获取第 0 和第 1 个字节
        # 使用 little-endian 将两个字节转换为整数
        ch1 = int.from_bytes(
            data[0:2],
            byteorder="little",
            signed=False
        )

        # ----------------------------------------------------
        # 提取 CH2 数据
        # ----------------------------------------------------

        # 获取第 2 和第 3 个字节
        # 使用 little-endian 将两个字节转换为整数
        ch2 = int.from_bytes(
            data[2:4],
            byteorder="little",
            signed=False
        )

        # 返回两个通道解析后的数值
        return ch1, ch2


    # --------------------------------------------------------
    # 3. 数据包测试
    # --------------------------------------------------------

    def test_parser(self):

        # 构造一个模拟 BLE 数据包
        # CH1 = 1007
        # CH2 = 2011
        #
        # 1007 = 0x03EF
        # 2011 = 0x07DB
        #
        # 小端字节序：
        # EF 03 DB 07

        test_data = bytes([0xEF, 0x03, 0xDB, 0x07])

        # 调用解析函数
        ch1, ch2 = self.parse_packet(test_data)

        # 输出解析结果
        print("Data Parser Test")
        print("----------------")
        print(f"CH1 = {ch1}")
        print(f"CH2 = {ch2}")


# ------------------------------------------------------------
# 4. 独立运行测试
# ------------------------------------------------------------

if __name__ == "__main__":

    # 创建解析器对象
    parser = DataParser()

    # 执行测试
    parser.test_parser()
